    def test_move_image(self):
        """Test case for move_image and list_move_targets

        """
        target_set = self.image_sets_api.create_image_set(
            body=ImageSet(name="test_images_move_target", team=self.team.id))
        product = self.product_api.create_product(
            body=Product(name="test_images_move", imagesets=[self.image_set.id], team=self.team.id))
        annotation_type = self.anno_type_api.create_annotation_type(
            body=AnnotationType(name="test_images_move", product=product.id,
                                vector_type=int(AnnotationType.VECTOR_TYPE.BOUNDING_BOX)))
        image = self.api.create_image(file_path="exact_sync/v1/test/images/Eosinophile.png",
                                      image_type=0, image_set=self.image_set.id).results[0]
        try:
            annotation = self.annotations_api.create_annotation(body=Annotation(
                annotation_type=annotation_type.id, image=image.id, unique_identifier=str(uuid.uuid4()),
                vector={"x1": 10, "y1": 10, "x2": 20, "y2": 20}))

            target_ids = [t['id'] for t in self.api.list_move_targets()]
            assert target_set.id in target_ids

            # the target image set does not offer the annotation type yet
            with self.assertRaises(ApiException) as context:
                self.api.move_image(id=image.id, target_imageset_id=target_set.id)
            assert context.exception.status == 409
            assert self.api.retrieve_image(id=image.id).image_set == self.image_set.id

            self.product_api.partial_update_product(id=product.id, imagesets=[self.image_set.id, target_set.id])
            result = self.api.move_image(id=image.id, target_imageset_id=target_set.id)

            assert result['id'] == image.id
            assert result['image_set'] == target_set.id
            assert self.api.retrieve_image(id=image.id).image_set == target_set.id
            annotations = self.annotations_api.list_annotations(image=image.id)
            assert [a.id for a in annotations.results] == [annotation.id]
        finally:
            self.api.destroy_image(id=image.id)
            self.anno_type_api.destroy_annotation_type(id=annotation_type.id)
            self.product_api.destroy_product(id=product.id)
            self.image_sets_api.destroy_image_set(id=target_set.id)

